#Requires -Version 7.0
[CmdletBinding()]
param(
    [string]$BaseUrl = "http://127.0.0.1:8000",
    [ValidateRange(5, 600)]
    [int]$TimeoutSeconds = 60
)

$ErrorActionPreference = "Stop"
$projectRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$api = $BaseUrl.TrimEnd("/") + "/api"

Write-Host "Checking API..."
$health = Invoke-RestMethod -Uri "$api/health" -Method Get
if ($health.status -ne "ok") { throw "API health check failed." }

$models = @(Invoke-RestMethod -Uri "$api/models" -Method Get)
$demoModel = $models | Where-Object { $_.is_demo -eq $true -and $_.is_available -eq $true } | Select-Object -First 1
if (-not $demoModel) { throw "No available demo model was returned by /api/models." }

$stamp = Get-Date -Format "yyyyMMdd-HHmmss-fff"
$projectBody = @{
    name = "Synthetic Demo $stamp"
    description = "Generated by scripts/demo-api.ps1; not research evidence."
} | ConvertTo-Json
$project = Invoke-RestMethod -Uri "$api/projects" -Method Post -ContentType "application/json" -Body $projectBody

$issuesPath = Join-Path $projectRoot "sample_data\issues.csv"
$commitsPath = Join-Path $projectRoot "sample_data\commits.csv"
$import = Invoke-RestMethod -Uri "$api/projects/$($project.id)/imports" -Method Post -Form @{
    issues_file = Get-Item -LiteralPath $issuesPath
    commits_file = Get-Item -LiteralPath $commitsPath
}

$profile = @($demoModel.calibration_profiles) | Select-Object -First 1
$runBody = @{
    project_id = $project.id
    dataset_revision_id = $import.revision.id
    model_release_id = $demoModel.id
    calibration_profile_id = if ($profile) { $profile.id } else { $null }
    mode = "recover"
    days_before = 3
    days_after = 14
    unresolved_window_days = 90
    max_candidates_per_issue = 200
} | ConvertTo-Json
$run = Invoke-RestMethod -Uri "$api/runs" -Method Post -ContentType "application/json" -Body $runBody

Write-Host "Queued run $($run.id); waiting for the worker..."
$deadline = (Get-Date).AddSeconds($TimeoutSeconds)
do {
    Start-Sleep -Milliseconds 500
    $run = Invoke-RestMethod -Uri "$api/runs/$($run.id)" -Method Get
    Write-Progress -Activity "Synthetic ACCS-Trace demo" -Status $run.stage -PercentComplete $run.progress
    if ($run.status -in @("failed", "cancelled", "interrupted")) {
        throw "Run ended with status '$($run.status)': $($run.error_message)"
    }
} while ($run.status -ne "completed" -and (Get-Date) -lt $deadline)
Write-Progress -Activity "Synthetic ACCS-Trace demo" -Completed

if ($run.status -ne "completed") {
    throw "Timed out after $TimeoutSeconds seconds while waiting for the worker."
}

$exportBody = @{ format = "csv"; include_rejected = $true } | ConvertTo-Json
$export = Invoke-RestMethod -Uri "$api/runs/$($run.id)/exports" -Method Post -ContentType "application/json" -Body $exportBody
$exportDir = Join-Path $projectRoot "data\demo-exports"
New-Item -ItemType Directory -Path $exportDir -Force | Out-Null
$downloadPath = Join-Path $exportDir "$($run.id).csv"
Invoke-WebRequest -Uri "$api/exports/$($export.id)/download" -OutFile $downloadPath

Write-Host "Synthetic workflow completed."
Write-Host "  Project:    $($project.id)"
Write-Host "  Run:        $($run.id)"
Write-Host "  Candidates: $($run.summary_json.candidate_count)"
Write-Host "  Recommended/Review/Rejected: $($run.summary_json.recommended)/$($run.summary_json.review)/$($run.summary_json.rejected)"
Write-Host "  Export:     $downloadPath"
Write-Warning "The deterministic demo runtime is not ACCS and these scores are not research evidence."
